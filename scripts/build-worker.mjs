/**
 * Bundles the Python worker (src/runtime/worker.ts) into one ES module and writes it as a string
 * constant (src/runtime/worker-source.generated.ts). The runtime starts the worker from a Blob of
 * that string, so a host's bundler never has to find, copy or transform a worker file.
 */
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const out = await build({
  entryPoints: ['src/runtime/worker.ts'],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  write: false,
});
const code = out.outputFiles[0].text;
writeFileSync(
  'src/runtime/worker-source.generated.ts',
  `// Generated by scripts/build-worker.mjs from worker.ts: do not edit.\nexport const WORKER_SOURCE = ${JSON.stringify(code)};\n`,
);
